// @vitest-environment node
// Python's random module runs on the core's generator and gives NodeBox 3's
// results for integer seeds. Needs the WASM module (see AGENTS.md).

import { describe, expect, it } from 'vitest';

// Vite's Electron plugin rewrites node: imports for the renderer.
const { existsSync, readFileSync } = process.getBuiltinModule('node:fs');
const { fileURLToPath } = process.getBuiltinModule('node:url');

const wasmFile = fileURLToPath(new URL('../../wasm/nodebox_electron_bg.wasm', import.meta.url));
const randomPy = fileURLToPath(new URL('../../src/python/random.py', import.meta.url));

// Jython 2.7.2 (NodeBox 3), with the seed passed as a port value:
// random() x3, uniform(10, 20), [randint(1, 6) x5], randrange(0, 100, 7),
// randrange(50), choice('abcdefghij'), shuffle(range(10)),
// sample(range(10), 3), random().
const JYTHON: Record<number, unknown[]> = {
  0: [0.7309677886325194, 0.24053641860444253, 0.6374174304980826, 15.504370116964473, [4, 2, 3, 6, 6], 98, 13, 'b', [5, 7, 2, 9, 3, 8, 6, 4, 0, 1], [4, 6, 5], 0.8172970787644881],
  42: [0.7275636870761607, 0.6832234788532503, 0.30871945576424553, 12.770784848012818, [4, 6, 3, 2, 3], 77, 45, 'e', [8, 2, 5, 0, 6, 9, 4, 1, 3, 7], [5, 9, 6], 0.03141823646822961],
  [-7]: [0.2692113789354663, 0.5036367859300293, 0.9511922182086185, 10.69598203701575, [5, 5, 2, 2, 4], 56, 11, 'c', [9, 0, 5, 4, 6, 8, 2, 3, 7, 1], [1, 8, 0], 0.3483289050658399],
  123456789: [0.6640381050356958, 0.4569517840062798, 0.39050648522821474, 18.933411570302397, [5, 3, 3, 3, 1], 21, 13, 'f', [0, 2, 7, 5, 9, 3, 8, 6, 4, 1], [7, 5, 3], 0.7149425786784425],
};

const SCRIPT = `
import random
r = random.Random(SEED)
report(r.random())
report(r.random())
report(r.random())
report(r.uniform(10, 20))
report([r.randint(1, 6) for _ in range(5)])
report(r.randrange(0, 100, 7))
report(r.randrange(50))
report(r.choice('abcdefghij'))
l = list(range(10))
r.shuffle(l)
report(l)
report(r.sample(range(10), 3))
report(r.random())
`;

describe.skipIf(!existsSync(wasmFile))('python random', () => {
  async function run(script: string): Promise<unknown[]> {
    // @ts-expect-error WASM module generated by wasm-pack
    const wasm = await import('../../wasm/nodebox_electron.js');
    wasm.initSync({ module: readFileSync(wasmFile) });
    // @ts-expect-error The package has no type declarations
    const { loadMicroPython } = await import('@micropython/micropython-webassembly-pyscript');
    const mp = await loadMicroPython({ stdout: () => {}, stderr: (s: string) => console.error(s) });
    mp.FS.mkdirTree('/lib');
    mp.FS.writeFile('/lib/random.py', readFileSync(randomPy, 'utf8'));
    mp.registerJsModule('_nodebox_random', { Random: (seed: number) => new wasm.WasmRandom(seed) });
    const values: unknown[] = [];
    mp.registerJsModule('_report', {
      // Lists come as JSON, everything else as a JS value.
      report: (v: unknown) => values.push(typeof v === 'string' && v.startsWith('[') ? JSON.parse(v) : v),
    });
    mp.runPython(
      'import json\nfrom _report import report as _report\n' +
        'def report(v):\n    _report(json.dumps(v) if isinstance(v, list) else v)\n' +
        script,
    );
    return values;
  }

  for (const [seed, expected] of Object.entries(JYTHON)) {
    it(`matches NodeBox 3 for seed ${seed}`, async () => {
      expect(await run(SCRIPT.replace('SEED', seed))).toEqual(expected);
    });
  }

  it('shares the module-level generator', async () => {
    const [a, b, c] = await run(`
import random
random.seed(42)
report(random.random())
random.seed(42)
report(random.random())
report(random.randint(1, 6))
`);
    expect(a).toBe(JYTHON[42][0]);
    expect(b).toBe(a);
    expect(c).toBe(1 + Math.floor((JYTHON[42][1] as number) * 6));
  });
});
