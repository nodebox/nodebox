// Embed the built-in NodeBox 3 node libraries (libraries/*/*.ndbx at the repository root) as
// string constants, so the core package can load them without file system access (browser,
// Cloudflare Worker, Electron renderer). The .ndbx files stay the single source of truth.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const librariesDir = path.resolve(here, "..", "..", "..", "libraries");
const outFile = path.resolve(here, "..", "src", "libraries", "builtin-ndbx.ts");

const names = fs
  .readdirSync(librariesDir)
  .filter((name) => fs.existsSync(path.join(librariesDir, name, `${name}.ndbx`)))
  .sort();

// Libraries the Java application cannot run (their functions are TypeScript) live in this package.
const localDir = path.resolve(here, "..", "libraries");
const localNames = fs
  .readdirSync(localDir)
  .filter((name) => name.endsWith(".ndbx"))
  .map((name) => name.replace(/\.ndbx$/, ""))
  .sort();

let out = "// Generated by scripts/embed-libraries.mjs from libraries/*/*.ndbx. Do not edit.\n\n";
out += "export const builtinLibrarySources: Record<string, string> = {\n";
for (const name of names) {
  const xml = fs.readFileSync(path.join(librariesDir, name, `${name}.ndbx`), "utf-8");
  out += `  ${JSON.stringify(name)}: ${JSON.stringify(xml)},\n`;
}
for (const name of localNames) {
  const xml = fs.readFileSync(path.join(localDir, `${name}.ndbx`), "utf-8");
  out += `  ${JSON.stringify(name)}: ${JSON.stringify(xml)},\n`;
}
out += "};\n";
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);

// The classic NodeBox Live core/g library: the metadata of its 172 functions. Their code lives in
// the g.js package, which the host passes in; only the declarations are needed to build the nodes.
const classicG = fs.readFileSync(path.resolve(here, "..", "libraries", "classic-g.json"), "utf-8");
const classicOut =
  "// Generated by scripts/embed-libraries.mjs from libraries/classic-g.json. Do not edit.\n\n" +
  'import type { ClassicProject } from "./classic-types";\n\n' +
  "export const classicCoreG: ClassicProject = " +
  classicG +
  ";\n";
fs.writeFileSync(path.resolve(here, "..", "src", "live", "classic-g.ts"), classicOut);
console.log(`Embedded ${names.length + localNames.length} libraries: ${[...names, ...localNames].join(", ")}`);
